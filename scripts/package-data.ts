// Writes the data modules of the npm package from the built set:
//
//   node scripts/package-data.ts   → src/generated/ids.ts   (groups and code points; small)
//                                    src/generated/meta.ts  (names and keywords; large)
//
// Run it after `node build.ts --sprites` changed dist/index.json, or after a version bump.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT } from "./common.ts";

interface Index {
  cell: number;
  groups: Array<{ id: string; label: string; sprite: string; cols: number; stickers: Array<[string, string, string]> }>;
}

const index: Index = JSON.parse(readFileSync(join(ROOT, "dist/index.json"), "utf8"));
const { version } = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8")) as { version: string };
const banner = "// Generated by scripts/package-data.ts from dist/index.json. Do not edit.\n";

mkdirSync(join(ROOT, "src/generated"), { recursive: true });

writeFileSync(
  join(ROOT, "src/generated/ids.ts"),
  `${banner}
/** Version of the package these files belong to. */
export const VERSION = ${JSON.stringify(version)};

/** Side of one cell of a sprite sheet, in px. */
export const CELL = ${index.cell};

/** Per group: id, label, cells per row of its sprite sheet, its emoji (code points, space-separated, in sheet order). */
export const GROUPS: ReadonlyArray<readonly [id: string, label: string, cols: number, emojis: string]> = [
${index.groups.map((g) => `  [${JSON.stringify(g.id)}, ${JSON.stringify(g.label)}, ${g.cols}, ${JSON.stringify(g.stickers.map((s) => s[0]).join(" "))}],`).join("\n")}
];
`,
);

writeFileSync(
  join(ROOT, "src/generated/meta.ts"),
  `${banner}
/** Code points → [name, keywords (comma-separated)]. */
export const META: Readonly<Record<string, readonly [name: string, keywords: string]>> = {
${index.groups.flatMap((g) => g.stickers.map(([u, n, k]) => `  ${JSON.stringify(u)}: [${JSON.stringify(n)}, ${JSON.stringify(k)}],`)).join("\n")}
};
`,
);

console.log(`package data: ${index.groups.reduce((a, g) => a + g.stickers.length, 0)} emoji in ${index.groups.length} groups, version ${version}`);
